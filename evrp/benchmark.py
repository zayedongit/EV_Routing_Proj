"""Reproducible experiment harness.

Everything a run depends on -- instance, fleet, battery, prices, solver, seed,
time limit -- is part of the :class:`~evrp.config.Scenario` that is written
next to the results, so a table in the README can be regenerated by replaying
the same file.  Results are always produced by the independent simulator, so an
"improvement" that quietly breaks feasibility shows up as an infeasible row
rather than as a better number.
"""

from __future__ import annotations

import json
import platform
import re
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable, Sequence

import pandas as pd

from evrp.config import Scenario
from evrp.instance import Instance, instance_from_scenario
from evrp.solution import Solution
from evrp.solvers import available, create
from evrp.solvers.base import SolverError

DEFAULT_INSTANCES = ("C101", "C201", "R101", "R201", "RC101", "RC201")

#: Standard Solomon fleet capacities (the benchmark's own convention).
SOLOMON_CAPACITY = {"C1": 200, "C2": 700, "R1": 200, "R2": 1000, "RC1": 200, "RC2": 1000}


def solomon_capacity(instance_name: str) -> int:
    """Capacity prescribed by the Solomon benchmark for an instance family.

    Getting this wrong makes instances silently infeasible: C101 has a total
    demand of 1810, so a fleet with the wrong 100-unit capacity can never serve
    it no matter how many vehicles are thrown at the problem.
    """
    match = re.match(r"^([A-Z]+)(\d)", instance_name.strip().upper())
    key = f"{match.group(1)}{match.group(2)}" if match else ""
    if key not in SOLOMON_CAPACITY:
        raise KeyError(
            f"unknown Solomon family for {instance_name!r}; "
            f"expected one of {sorted(SOLOMON_CAPACITY)}"
        )
    return SOLOMON_CAPACITY[key]


@dataclass
class BenchmarkRow:
    scenario: str
    instance: str
    solver: str
    seed: int
    time_limit_s: float
    runtime_s: float
    feasible: bool
    distance_km: float
    vehicles: int
    customers_served: int
    customers_total: int
    charging_stops: int
    energy_kwh: float
    charged_kwh: float
    charge_time_min: float
    min_soc_kwh: float
    violations: int
    battery_kwh: float
    status: str
    note: str = ""

    def to_dict(self) -> dict[str, Any]:
        return dict(self.__dict__)


@dataclass
class BenchmarkResult:
    rows: list[BenchmarkRow] = field(default_factory=list)
    solutions: dict[tuple[str, str, str], Solution] = field(default_factory=dict)
    environment: dict[str, Any] = field(default_factory=dict)

    def to_frame(self) -> pd.DataFrame:
        return pd.DataFrame([r.to_dict() for r in self.rows])

    def save(self, directory: str | Path) -> dict[str, Path]:
        out = Path(directory)
        out.mkdir(parents=True, exist_ok=True)
        frame = self.to_frame()
        csv_path = out / "benchmark.csv"
        frame.to_csv(csv_path, index=False)
        env_path = out / "environment.json"
        env_path.write_text(json.dumps(self.environment, indent=2) + "\n")
        md_path = out / "benchmark.md"
        md_path.write_text(to_markdown(frame))
        return {"csv": csv_path, "markdown": md_path, "environment": env_path}


def environment_info() -> dict[str, Any]:
    try:
        from ortools import __version__ as ortools_version
    except Exception:  # pragma: no cover
        ortools_version = "unknown"
    return {
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "machine": platform.machine(),
        "processor": platform.processor(),
        "ortools": ortools_version,
        "pandas": pd.__version__,
        "timestamp_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }


def build_row(
    scenario: Scenario,
    instance: Instance,
    solution: Solution,
    note: str = "",
) -> BenchmarkRow:
    m = solution.metrics
    return BenchmarkRow(
        scenario=scenario.name,
        instance=instance.name,
        solver=solution.solver,
        seed=scenario.solver.seed,
        time_limit_s=scenario.solver.time_limit_s,
        runtime_s=round(solution.runtime_s, 3),
        feasible=solution.feasible,
        distance_km=round(m.total_distance, 3),
        vehicles=m.vehicles_used,
        customers_served=m.customers_served,
        customers_total=m.customers_total,
        charging_stops=m.charging_stops,
        energy_kwh=round(m.energy_consumed_kwh, 3),
        charged_kwh=round(m.energy_charged_kwh, 3),
        charge_time_min=round(m.total_charge_time, 2),
        min_soc_kwh=round(m.min_soc_kwh, 3),
        violations=m.n_violations,
        battery_kwh=instance.vehicle.battery_kwh,
        status=solution.status,
        note=note,
    )


def run_benchmark(
    scenarios: Sequence[Scenario],
    solvers: Iterable[str] = ("ortools", "savings", "insertion", "insertion-ls"),
    data_dir: str | Path = "data",
    keep_solutions: bool = False,
    verbose: bool = True,
) -> BenchmarkResult:
    """Run every (scenario x solver) pair and collect verified metrics."""
    solvers = list(solvers)
    unknown = [s for s in solvers if s not in available()]
    if unknown:
        raise ValueError(f"unknown solver(s) {unknown}; available: {available()}")

    result = BenchmarkResult(environment=environment_info())
    for scenario in scenarios:
        scenario.validate()
        path = Path(scenario.instance_file)
        if not path.is_absolute() and not path.exists():
            path = Path(data_dir) / path.name
        instance = instance_from_scenario(scenario, source=str(path))

        for name in solvers:
            solver = create(
                name,
                solver_config=scenario.solver,
                energy_config=scenario.energy,
                charging_config=scenario.charging,
            )
            try:
                solution = solver.solve(instance)
                note = ""
            except SolverError as exc:
                note = f"solver error: {exc}"[:200]
                solution = Solution(
                    instance_name=instance.name, solver=name, status="error"
                ).evaluate(instance, scenario.energy, scenario.charging)
            row = build_row(scenario, instance, solution, note)
            result.rows.append(row)
            if keep_solutions:
                result.solutions[(scenario.name, instance.name, name)] = solution
            if verbose:
                print(f"  {solution.summary()}", flush=True)
    return result


def make_scenarios(
    instances: Sequence[str] = DEFAULT_INSTANCES,
    data_dir: str | Path = "data",
    battery_kwh: float = 40.0,
    n_stations: int = 6,
    fleet_size: int = 25,
    time_limit_s: float = 30.0,
    seed: int = 42,
    name_prefix: str = "base",
    station_copies: int = 2,
    station_strategy: str = "kmeans",
    station_power_kw: float = 50.0,
    reserve_soc: float = 0.10,
    **scenario_overrides: Any,
) -> list[Scenario]:
    """One scenario per instance, with the Solomon capacity for its family.

    Payload capacity is deliberately *not* a parameter: a benchmark comparison
    is only meaningful at the capacity the Solomon family prescribes, so it is
    always taken from :func:`solomon_capacity`.  Everything else the caller can
    vary is passed through -- silently dropping a knob here means a command
    line that looks like it configured a run but did not.
    """
    from evrp.config import SolverConfig, VehicleSpec

    out: list[Scenario] = []
    for inst in instances:
        capacity = solomon_capacity(inst)
        vehicle = VehicleSpec(
            payload_capacity=capacity,
            battery_kwh=battery_kwh,
            reserve_soc=reserve_soc,
        )
        out.append(
            Scenario(
                name=f"{name_prefix}-{inst}",
                instance_file=str(Path(data_dir) / f"{inst}.csv"),
                fleet_size=fleet_size,
                n_stations=n_stations,
                station_strategy=station_strategy,
                station_power_kw=station_power_kw,
                vehicle=vehicle,
                solver=SolverConfig(
                    time_limit_s=time_limit_s,
                    seed=seed,
                    station_copies=station_copies,
                ),
                **scenario_overrides,
            )
        )
    return out


def to_markdown(frame: pd.DataFrame, columns: Sequence[str] | None = None) -> str:
    """Render a results frame as a GitHub-flavoured Markdown table."""
    if frame.empty:
        return "_no results_\n"
    cols = list(columns) if columns else list(frame.columns)
    lines = ["| " + " | ".join(cols) + " |",
             "| " + " | ".join("---" for _ in cols) + " |"]
    for _, row in frame.iterrows():
        cells = []
        for c in cols:
            v = row[c]
            cells.append(f"{v:.2f}" if isinstance(v, float) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def summarise(frame: pd.DataFrame) -> pd.DataFrame:
    """Per-solver aggregate: quality, feasibility rate and runtime."""
    if frame.empty:
        return frame
    grouped = frame.groupby("solver", as_index=False).agg(
        runs=("instance", "count"),
        feasible=("feasible", "sum"),
        mean_distance_km=("distance_km", "mean"),
        mean_vehicles=("vehicles", "mean"),
        mean_runtime_s=("runtime_s", "mean"),
        mean_charging_stops=("charging_stops", "mean"),
    )
    grouped["feasible_rate"] = grouped["feasible"] / grouped["runs"]
    return grouped


def gap_table(frame: pd.DataFrame, reference_solver: str = "ortools") -> pd.DataFrame:
    """Distance of each solver relative to a reference solver, per instance.

    Only rows that both solvers solved feasibly are compared, so the gap
    measures solution quality and not "who was allowed to give up".
    """
    feasible = frame[frame["feasible"]]
    ref = feasible[feasible["solver"] == reference_solver][["instance", "distance_km"]]
    ref = ref.rename(columns={"distance_km": "reference_km"})
    merged = feasible.merge(ref, on="instance", how="inner")
    merged["gap_pct"] = 100.0 * (merged["distance_km"] - merged["reference_km"]) / merged["reference_km"]
    return merged[
        ["instance", "solver", "distance_km", "reference_km", "gap_pct", "runtime_s"]
    ].sort_values(["instance", "gap_pct"])
